export const STORE_COUNTRY_CODES: readonly string[] = STORE_COUNTRIES.map(
	([alpha2]) => alpha2,
);

const ALPHA2_BY_ALPHA3 = new Map(
	STORE_COUNTRIES.map(([alpha2, alpha3]) => [alpha3, alpha2]),
);
const ALPHA3_BY_ALPHA2 = new Map(
	STORE_COUNTRIES.map(([alpha2, alpha3]) => [alpha2, alpha3]),
);
const ALPHA2_LENGTH = 2;
const ALPHA3_LENGTH = 3;

/**
 * Lower-case alpha-2 country for a review territory, whichever form the
 * store used: App Store Connect sends "USA", the public scrapers "us".
 * Null when the territory is missing or unknown.
 */
export function countryFromTerritory(
	territory: string | null | undefined,
): string | null {
	if (!territory) return null;
	const trimmed = territory.trim();
	if (trimmed.length === ALPHA2_LENGTH) return trimmed.toLowerCase();
	if (trimmed.length === ALPHA3_LENGTH) {
		return ALPHA2_BY_ALPHA3.get(trimmed.toUpperCase()) ?? null;
	}
	return null;
}

/** Upper-case alpha-3 for an alpha-2 country, or null when unknown. */
export function alpha3ForCountry(country: string): string | null {
	return ALPHA3_BY_ALPHA2.get(country.toLowerCase()) ?? null;
}
